import { describe, expect, it } from "vitest";
import { createDemoRuntime, DEMO_PASSWORD } from "./index";
describe("synthetic demo core loop", () => {
    it("starts signed out, projects safe discovery fields, and isolates factory state", async () => {
        const demo = createDemoRuntime();
        expect(await demo.api.getSession()).toBeNull();
        demo.controls.enter("member");
        const result = await demo.api.searchMembers({});
        expect(result.totalItems).toBeGreaterThan(6);
        expect(result.items.some((p) => p.id === "demo-asha")).toBe(false);
        expect(result.items.every((p) => !("email" in p) && !("settings" in p) && !("password" in p))).toBe(true);
        const profile = await demo.api.getMember("demo-mira");
        expect(profile.connection).toEqual({ status: "connected", conversationId: "demo-conversation-mira" });
        profile.languages.push("Mutated client response");
        expect((await demo.api.getMember("demo-mira")).languages).toEqual(["English"]);
        expect(await createDemoRuntime().api.getSession()).toBeNull();
    });
    it("requires acceptance, rejects self/duplicate requests, and enforces actor ownership", async () => {
        const { api, controls } = createDemoRuntime();
        controls.enter("member");
        await expect(api.sendRequest("demo-asha", "A synthetic introduction.")).rejects.toMatchObject({ kind: "conflict" });
        const request = await api.sendRequest("demo-noor", "Could you share your first-week experience?");
        await expect(api.sendRequest("demo-noor", "Could you share your first-week experience?")).rejects.toMatchObject({ kind: "conflict" });
        await expect(api.acceptRequest(request.id)).rejects.toMatchObject({ kind: "not_found" });
        controls.enter("helper");
        await expect(api.acceptRequest("demo-request-leo")).rejects.toMatchObject({ kind: "not_found" });
        controls.enter("member");
        const accepted = await api.acceptRequest("demo-request-leo");
        expect(accepted.member.id).toBe("demo-leo");
        expect(await api.sendMessage(accepted.conversationId, { clientMessageId: "new-thread-1", body: "Thanks for connecting." })).toMatchObject({ senderId: "demo-asha" });
        controls.enter("admin");
        await expect(api.getConversation(accepted.conversationId)).rejects.toMatchObject({ kind: "not_found" });
    });
    it("retries messages once, rejects changed payload keys, and preserves blocked history", async () => {
        const { api, controls } = createDemoRuntime();
        controls.enter("member");
        const thread = "demo-conversation-mira";
        controls.setScenario("send_failure");
        const input = { clientMessageId: "retry-key", body: "A question about the first week." };
        await expect(api.sendMessage(thread, input)).rejects.toMatchObject({ kind: "unavailable" });
        expect((await api.listMessages(thread)).items).toHaveLength(2);
        const sent = await api.sendMessage(thread, input);
        expect(await api.sendMessage(thread, input)).toEqual(sent);
        expect((await api.listMessages(thread)).items).toHaveLength(3);
        await expect(api.sendMessage(thread, { ...input, body: "Different text." })).rejects.toMatchObject({ kind: "conflict" });
        await api.blockMember("demo-mira");
        expect((await api.searchMembers({})).items.some((p) => p.id === "demo-mira")).toBe(false);
        expect(await api.getConversation(thread)).toMatchObject({ restriction: "blocked_by_you" });
        expect((await api.listMessages(thread)).items).toHaveLength(3);
        await expect(api.sendMessage(thread, { clientMessageId: "blocked-new", body: "New contact is denied." })).rejects.toMatchObject({ kind: "forbidden" });
        controls.enter("helper");
        expect(await api.getConversation(thread)).toMatchObject({ restriction: "unavailable" });
        await expect(api.getMember("demo-asha")).rejects.toMatchObject({ kind: "not_found" });
        await expect(api.sendMessage(thread, { clientMessageId: "reverse-block", body: "Denied in either direction." })).rejects.toMatchObject({ kind: "forbidden" });
    });
    it("scopes report evidence and idempotency, and authorizes moderation", async () => {
        const { api, controls } = createDemoRuntime();
        controls.enter("member");
        const input = { clientRequestId: "case-1", memberId: "demo-mira", messageId: "demo-message-2", reason: "other" as const, details: "Synthetic report for testing." };
        const receipt = await api.createReport(input);
        expect(await api.createReport(input)).toEqual(receipt);
        await expect(api.createReport({ ...input, details: "Changed details." })).rejects.toMatchObject({ kind: "conflict" });
        await expect(api.createReport({ ...input, clientRequestId: "case-2", memberId: "demo-noor" })).rejects.toMatchObject({ kind: "not_found" });
        await expect(api.getReport(receipt.id)).rejects.toMatchObject({ kind: "forbidden" });
        controls.enter("admin");
        expect((await api.listReports({ status: "open" })).totalItems).toBe(2);
        expect((await api.getReport(receipt.id)).reportedMessage).toMatchObject({ id: "demo-message-2" });
        await api.assignReportToMe(receipt.id);
        expect(await api.resolveReport(receipt.id, { outcome: "no_violation", note: "Synthetic evidence reviewed, no actual case." })).toMatchObject({ status: "resolved" });
    });
    it("demonstrates register/verification/reset and genuinely expires session access", async () => {
        let time = Date.parse("2026-10-16T10:00:00Z");
        const { api, controls } = createDemoRuntime(() => time);
        const credentials = { email: "fiction@example.test", password: DEMO_PASSWORD };
        await api.register({ ...credentials, displayName: "Fictional Member", acceptTerms: true, confirmAdult: true });
        await expect(api.login(credentials)).rejects.toMatchObject({ code: "email_unverified" });
        const token = new URL(controls.state.latestLink!, "https://demo.test").searchParams.get("token")!;
        await api.verifyEmail(token);
        await expect(api.verifyEmail(token)).rejects.toMatchObject({ kind: "validation" });
        expect(await api.login(credentials)).toMatchObject({ onboardingComplete: false });
        await api.updateOwnProfile({ journey: "preparing", country: "Germany", lookingFor: "First-week questions", helpTopics: ["first-weeks"], completeOnboarding: true });
        expect(await api.getSession()).toMatchObject({ onboardingComplete: true });
        await api.requestPasswordReset(credentials.email);
        const reset = new URL(controls.state.latestLink!, "https://demo.test").searchParams.get("token")!;
        await api.resetPassword(reset, "NewDemoOnly123!");
        expect(await api.getSession()).toBeNull();
        await api.login({ ...credentials, password: "NewDemoOnly123!" });
        time += 60 * 60000;
        expect(await api.getSession()).toBeNull();
        await expect(api.getOwnProfile()).rejects.toMatchObject({ kind: "unauthorized" });
        controls.enter("member");
        controls.setScenario("unavailable");
        await expect(api.searchMembers({})).rejects.toMatchObject({ kind: "unavailable" });
        controls.setScenario("normal");
        controls.reset();
        expect(await api.getSession()).toBeNull();
    });
});
